/* eslint-disable jsx-a11y/alt-text */
import { renderToBuffer, Document, Page, Text, View, StyleSheet, Font } from '@react-pdf/renderer';
import * as React from 'react';

// Note: Arabic shaping in @react-pdf works best with a TTF that supports Arabic.
// In production register Noto Kufi Arabic via Font.register({ family, src }).
// For MVP we rely on the default fonts and rtl text direction at the row level.

const styles = StyleSheet.create({
  page: {
    padding: 36,
    fontSize: 11,
    color: '#1a1a2e',
    direction: 'rtl' as any,
    fontFamily: 'Helvetica',
  },
  header: {
    flexDirection: 'row',
    justifyContent: 'space-between',
    marginBottom: 16,
    paddingBottom: 10,
    borderBottom: '2 solid #1E3A5F',
  },
  brand: { fontSize: 18, color: '#1E3A5F' },
  meta: { textAlign: 'right' as any, fontSize: 10, color: '#666' },
  section: { marginBottom: 12 },
  label: { color: '#666', fontSize: 9 },
  value: { fontSize: 11 },
  table: { marginTop: 12, marginBottom: 12, border: '1 solid #ddd' },
  row: { flexDirection: 'row', borderBottom: '1 solid #eee' },
  th: { padding: 6, backgroundColor: '#f5f5f5', fontSize: 10, color: '#555' },
  td: { padding: 6, fontSize: 10 },
  total: { textAlign: 'right' as any, fontSize: 14, marginTop: 8, color: '#1E3A5F' },
  footer: { marginTop: 28, fontSize: 9, color: '#888', textAlign: 'center' as any },
});

type Item = { description: string; quantity: number; unit_price: number };

export async function renderInvoicePdf({
  invoice,
  teacher,
}: {
  invoice: any;
  teacher: any;
}): Promise<Buffer> {
  const items: Item[] = Array.isArray(invoice.items) ? invoice.items : [];

  const Doc = (
    <Document title={`Invoice ${invoice.invoice_number}`}>
      <Page size="A4" style={styles.page}>
        <View style={styles.header}>
          <View>
            <Text style={styles.brand}>{teacher?.name_en ?? teacher?.name_ar ?? 'Ostazna'}</Text>
            <Text style={{ fontSize: 9, color: '#666', marginTop: 2 }}>
              {teacher?.subdomain ? `${teacher.subdomain}.ostazna.com` : 'ostazna.com'}
            </Text>
          </View>
          <View style={styles.meta}>
            <Text style={{ fontSize: 14 }}>Invoice / فاتورة</Text>
            <Text>{invoice.invoice_number}</Text>
            <Text>{new Date(invoice.issued_at).toISOString().slice(0, 10)}</Text>
          </View>
        </View>

        <View style={styles.section}>
          <Text style={styles.label}>To / للسيد</Text>
          <Text style={styles.value}>
            {invoice.student?.name_en ?? invoice.student?.name_ar ?? '—'}
          </Text>
          {invoice.student?.parent_phone && (
            <Text style={{ fontSize: 9, color: '#666' }}>{invoice.student.parent_phone}</Text>
          )}
        </View>

        <View style={styles.table}>
          <View style={styles.row}>
            <Text style={[styles.th, { flex: 4 }]}>Description</Text>
            <Text style={[styles.th, { flex: 1, textAlign: 'center' }]}>Qty</Text>
            <Text style={[styles.th, { flex: 2, textAlign: 'right' }]}>Unit (EGP)</Text>
            <Text style={[styles.th, { flex: 2, textAlign: 'right' }]}>Total</Text>
          </View>
          {items.map((it, i) => (
            <View key={i} style={styles.row}>
              <Text style={[styles.td, { flex: 4 }]}>{it.description}</Text>
              <Text style={[styles.td, { flex: 1, textAlign: 'center' }]}>{it.quantity}</Text>
              <Text style={[styles.td, { flex: 2, textAlign: 'right' }]}>{it.unit_price.toFixed(2)}</Text>
              <Text style={[styles.td, { flex: 2, textAlign: 'right' }]}>{(it.quantity * it.unit_price).toFixed(2)}</Text>
            </View>
          ))}
        </View>

        <Text style={styles.total}>Total: {Number(invoice.amount).toFixed(2)} EGP</Text>

        {invoice.notes && (
          <View style={styles.section}>
            <Text style={styles.label}>Notes</Text>
            <Text style={styles.value}>{invoice.notes}</Text>
          </View>
        )}

        <Text style={styles.footer}>
          Generated by Ostazna · ostazna.com
        </Text>
      </Page>
    </Document>
  );

  return await renderToBuffer(Doc);
}
